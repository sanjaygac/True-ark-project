const STORAGE_KEY = 'trueark_property_master_records';

export function getStoredProperties() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_PROPERTIES));
      return INITIAL_PROPERTIES;
    }
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : INITIAL_PROPERTIES;
  } catch (err) {
    return INITIAL_PROPERTIES;
  }
}

export function saveStoredProperties(properties) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(properties));
  } catch (err) {
    console.error('Failed to save properties to localStorage:', err);
  }
}
